#!/usr/bin/env node
/**
 * build-catalog — generate the skill catalog in README.md from the SKILL.md
 * files themselves, so the README can never drift from what ships.
 *
 *   node scripts/build-catalog.mjs          # rewrite the block in README.md
 *   node scripts/build-catalog.mjs --check  # exit 1 if README is out of date (CI)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { findSkills } from "./install.mjs";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const README = join(REPO, "README.md");
const START = "<!-- catalog:start -->";
const END = "<!-- catalog:end -->";
const ORDER = ["koka", "gtm-strategy", "content-engineer", "linkedin-content", "linkedin-ads", "linkedin", "engagement-intelligence", "signal-sourcer", "list-building", "cold-email", "personalization", "signal-outbound", "sdr-tools", "ai-search-visibility"];

function meta(dir) {
  const body = readFileSync(join(dir, "SKILL.md"), "utf8");
  const fm = (body.match(/^---\n([\s\S]*?)\n---/) || [])[1] || "";
  const field = (k) => ((fm.match(new RegExp(`^${k}:\\s*(.+)$`, "m")) || [])[1] || "").replace(/^"|"$/g, "").trim();
  const description = field("description");
  const first = description.split(/(?<=[.!?])\s+(?=[A-Z])/)[0].replace(/\s+—\s+/g, " — ");
  const scriptsDir = join(dir, "scripts");
  const tools = existsSync(scriptsDir) ? readdirSync(scriptsDir).filter((f) => f.endsWith(".mjs")) : [];
  const parentDir = basename(dirname(dirname(dirname(dir))));
  const isSub = basename(dirname(dir)) === "skills" && basename(dirname(dirname(dir))) === ".claude";
  return { name: field("name"), first, tools, isSub, parent: isSub ? parentDir : null, path: relative(REPO, dir) };
}

export function buildCatalog() {
  const all = findSkills(REPO).map(meta);
  const masters = all.filter((s) => !s.isSub).sort((a, b) => ORDER.indexOf(a.name) - ORDER.indexOf(b.name));
  const lines = [START, "", "| Skill | Type | What it does | Runnable tool |", "|---|---|---|---|"];
  for (const m of masters) {
    lines.push(`| [**${m.name}**](${m.path}/SKILL.md) | ${m.name === "koka" ? "entry point" : "orchestrator"} | ${m.first} | ${m.tools.map((t) => `\`${t}\``).join(", ") || "—"} |`);
    for (const s of all.filter((x) => x.parent === m.name).sort((a, b) => a.name.localeCompare(b.name))) {
      lines.push(`| ↳ [${s.name}](${s.path}/SKILL.md) | sub-skill | ${s.first} | ${s.tools.map((t) => `\`${t}\``).join(", ") || "—"} |`);
    }
  }
  const toolCount = all.reduce((n, s) => n + s.tools.length, 0);
  lines.push("", `_${all.length} skills · ${masters.length - 1} orchestrators + 1 entry point · ${toolCount} runnable tools · generated by \`scripts/build-catalog.mjs\`_`, "", END);
  return lines.join("\n");
}

export function renderReadme(readme = readFileSync(README, "utf8")) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < 0) throw new Error("README.md is missing the catalog markers");
  const all = findSkills(REPO).map(meta);
  const tools = all.reduce((n, s) => n + s.tools.length, 0);
  return (readme.slice(0, a) + buildCatalog() + readme.slice(b + END.length))
    .replace(/badge\/skills-\d+-/, `badge/skills-${all.length}-`)
    .replace(/alt="\d+ skills"/, `alt="${all.length} skills"`)
    .replace(/badge\/runnable%20tools-\d+-/, `badge/runnable%20tools-${tools}-`)
    .replace(/alt="\d+ tools"/, `alt="${tools} tools"`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const current = readFileSync(README, "utf8");
  const next = renderReadme(current);
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error("README catalog is out of date — run: node scripts/build-catalog.mjs");
      process.exit(1);
    }
    console.log("catalog: README in sync");
  } else {
    writeFileSync(README, next);
    console.log("catalog: README updated");
  }
}
